const publicSeoTypes = new Set([
  'landing',
  'faqHub',
  'faq',
  'template',
  'authorityTemplate',
  'sampleHub',
  'sample',
  'authoritySample',
  'calculator',
  'guide',
])

export function normalizeSeoPath(path = '/') {
  const cleanPath = String(path || '/').split('?')[0].split('#')[0] || '/'
  if (cleanPath === '/') {
    return '/'
  }

  return cleanPath.replace(/\/+$/, '') || '/'
}

export function isPublicSeoRoute(path = '/') {
  const route = seoRouteMeta[normalizeSeoPath(path)]
  return Boolean(route && publicSeoTypes.has(route.type))
}

export function getCanonicalUrl(path = '/') {
  const normalizedPath = normalizeSeoPath(path)
  return `${siteOrigin}${normalizedPath === '/' ? '/' : normalizedPath}`
}

export function getSeoMetaForPath(path = '/', legalPage) {
  const normalizedPath = normalizeSeoPath(path)
  const routeMeta = seoRouteMeta[normalizedPath]

  if (routeMeta) {
    return {
      ...routeMeta,
      path: normalizedPath,
      canonical: getCanonicalUrl(normalizedPath),
      image: `${siteOrigin}/fbply-logo.png`,
    }
  }

  if (legalPage) {
    return {
      title: `FBPly | ${legalPage.title}`,
      description: legalPage.summary,
      breadcrumbLabel: legalPage.title,
      type: 'legal',
      path: normalizedPath,
      canonical: getCanonicalUrl(normalizedPath),
      image: `${siteOrigin}/fbply-logo.png`,
    }
  }

  return {
    ...seoRouteMeta['/'],
    path: '/',
    canonical: getCanonicalUrl('/'),
    image: `${siteOrigin}/fbply-logo.png`,
  }
}

