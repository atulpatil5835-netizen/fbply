function webPageSchema(meta) {
  return {
    '@type': 'WebPage',
    '@id': `${meta.canonical}#webpage`,
    url: meta.canonical,
    name: meta.title,
    description: meta.description,
    isPartOf: {
      '@id': `${siteOrigin}/#website`,
    },
    about: {
      '@id': `${siteOrigin}/#software`,
    },
    primaryImageOfPage: {
      '@type': 'ImageObject',
      url: meta.image,
    },
    dateModified: '2026-06-02',
  }
}

function breadcrumbSchema(meta) {
  const items = [
    {
      '@type': 'ListItem',
      position: 1,
      name: siteName,
      item: `${siteOrigin}/`,
    },
  ]

  if (meta.path !== '/') {
    items.push({
      '@type': 'ListItem',
      position: 2,
      name: meta.breadcrumbLabel || meta.title,
      item: meta.canonical,
    })
  }

  return {
    '@type': 'BreadcrumbList',
    '@id': `${meta.canonical}#breadcrumb`,
    itemListElement: items,
  }
}

export function buildStructuredDataForPath(path = '/', legalPage, extraSchemas = []) {
  const meta = getSeoMetaForPath(path, legalPage)
  const schemas = [
    organizationSchema(),
    websiteSchema(),
    softwareApplicationSchema(),
    webPageSchema(meta),
    breadcrumbSchema(meta),
    ...extraSchemas,
  ]

  return {
    '@context': 'https://schema.org',
    '@graph': schemas,
  }
}

function setMetaTag(attribute, key, content) {
  if (!content || typeof document === 'undefined') {
    return
  }

  let element = document.head.querySelector(`meta[${attribute}="${key}"]`)

  if (!element) {
    element = document.createElement('meta')
    element.setAttribute(attribute, key)
    document.head.appendChild(element)
  }

  element.setAttribute('content', content)
}

function setCanonicalLink(href) {
  if (!href || typeof document === 'undefined') {
    return
  }

  let element = document.head.querySelector('link[rel="canonical"]')

  if (!element) {
    element = document.createElement('link')
    element.setAttribute('rel', 'canonical')
    document.head.appendChild(element)
  }

  element.setAttribute('href', href)
}

function setJsonLd(structuredData) {
  if (typeof document === 'undefined') {
    return
  }

  let element = document.getElementById('fbply-jsonld')

  if (!element) {
    element = document.createElement('script')
    element.id = 'fbply-jsonld'
    element.type = 'application/ld+json'
    document.head.appendChild(element)
  }

  element.textContent = JSON.stringify(structuredData)
}

export function applySeoMetadata(path = '/', legalPage, extraSchemas = []) {
  if (typeof document === 'undefined') {
    return
  }

  const meta = getSeoMetaForPath(path, legalPage)

  document.title = meta.title
  setMetaTag('name', 'description', meta.description)
  setMetaTag('name', 'robots', 'index,follow,max-image-preview:large')
  setMetaTag(
    'name',
    'keywords',
    'budget planner, trip expense splitter, financial report generator, bank statement analyzer, shared expense calculator',
  )
  setCanonicalLink(meta.canonical)
  setMetaTag('property', 'og:url', meta.canonical)
  setMetaTag('property', 'og:type', 'website')
  setMetaTag('property', 'og:title', meta.title)
  setMetaTag('property', 'og:description', meta.description)
  setMetaTag('property', 'og:image', meta.image)
  setMetaTag('property', 'og:site_name', siteName)
  setMetaTag('name', 'twitter:card', 'summary_large_image')
  setMetaTag('name', 'twitter:title', meta.title)
  setMetaTag('name', 'twitter:description', meta.description)
  setMetaTag('name', 'twitter:image', meta.image)
  setJsonLd(buildStructuredDataForPath(path, legalPage, extraSchemas))
}
